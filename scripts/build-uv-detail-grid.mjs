/** Build one lazy production script from the reusable UV core + texture-detail adapter. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const core=fs.readFileSync(path.join(root,'js/uv-generation-roundtrip.mjs'),'utf8');
const adapter=fs.readFileSync(path.join(root,'js/uv-detail-grid.mjs'),'utf8');
const imp="import {createPlan,loadPlan,pack,unpack} from './uv-generation-roundtrip.mjs';";
if(!adapter.startsWith(imp))throw Error('Unexpected UV adapter import; review bundler');
let source=core;
for(const fn of ['createPlan','loadPlan','pack','unpack','estimateShift']){
 const signature='export function '+fn+'(';
 if(!source.includes(signature))throw Error('Missing UV core export '+fn);
 source=source.replace(signature,'function '+fn+'(');
}
if(/^\s*(?:export|import)\b/m.test(source)||/^\s*(?:export|import)\b/m.test(adapter.slice(imp.length)))throw Error('Unhandled module export/import');
const content='/* Generated by scripts/build-uv-detail-grid.mjs. Edit source .mjs files, not this bundle. */\n(()=>{\n\'use strict\';\n'+source+'\n'+adapter.slice(imp.length)+'\n})();\n';
const out=path.join(root,'js/uv-detail-grid.bundle.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(out)||fs.readFileSync(out,'utf8')!==content)throw Error('Stale UV detail production bundle');
 console.log('PASS UV detail production bundle freshness');
}else{fs.writeFileSync(out,content);console.log('Bundled UV detail adapter',content.length);}
