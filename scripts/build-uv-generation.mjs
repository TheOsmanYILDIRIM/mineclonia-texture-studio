/** Dependency-free bundler for the isolated UV generation studio's two ES modules.
 * Keep source modular; deploy only the single-file IIFE compiled here.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const rd=p=>fs.readFileSync(path.join(root,p),'utf8');
const core=rd('js/uv-generation-roundtrip.mjs');
const ui=rd('js/uv-generation-ui.mjs');
const importLine="import {createPlan,loadPlan,pack,unpack} from './uv-generation-roundtrip.mjs';";
if(!ui.startsWith(importLine))throw Error('Unexpected UV UI imports: update bundler explicitly');
const expected=['createPlan','loadPlan','pack','unpack','estimateShift'];
let source=core;
for(const fn of expected){const exact=`export function ${fn}(`;
 if(!source.includes(exact))throw Error('Missing expected core export: '+fn);
 source=source.replace(exact,`function ${fn}(`);
}
if(/\b(?:export|import)\s+(?:function|const|from|\{)/.test(source))throw Error('Unhandled core module export/import');
const body=ui.slice(importLine.length);
if(/^\s*(?:import|export)\b/m.test(body))throw Error('Unhandled UI module import/export');
const bundled=`/* Generated by scripts/build-uv-generation.mjs. Edit source .mjs files, not this bundle. */\n(()=>{\n'use strict';\n${source}\n${body}\n})();\n`;
const dest=path.join(root,'js/uv-generation.bundle.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==bundled)throw Error('UV production bundle stale; run node scripts/build-uv-generation.mjs');
 console.log('PASS UV generation single-file bundle matches sources');
}else{
 fs.writeFileSync(dest,bundled);console.log('Bundled',dest,bundled.length,'bytes');
}
